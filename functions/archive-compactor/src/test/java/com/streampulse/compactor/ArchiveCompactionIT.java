/**
 * End to end through the function catalog against moto.
 *
 * <p>NO service writes raw events to the archive yet, so every object here is generated by this
 * test. What this proves: the compaction sequence works through the real SDK calls (list,
 * stream, upload, re-read, delete). What it does not: behaviour at real volume, real S3
 * consistency, permissions (ADR-0003).
 */
@SpringBootTest(properties = {"compactor.bucket=" + ArchiveCompactionIT.BUCKET})
@Import(ArchiveCompactionIT.ClockConfig.class)
@Testcontainers
class ArchiveCompactionIT {

    static final String BUCKET = "archive-it";

    @Container
    static final GenericContainer<?> MOTO =
            new GenericContainer<>(DockerImageName.parse("motoserver/moto:5.2.2")).withExposedPorts(5000);

    /** A clock the test can move: moto stamps LastModified with the real time, so "later" is simulated here. */
    static final class MovableClock extends Clock {
        private volatile Instant now = Instant.now();

        void set(Instant instant) {
            this.now = instant;
        }

        @Override
        public ZoneId getZone() {
            return ZoneId.of("UTC");
        }

        @Override
        public Clock withZone(ZoneId zone) {
            return this;
        }

        @Override
        public Instant instant() {
            return now;
        }
    }

    @TestConfiguration
    static class ClockConfig {
        @Bean
        @Primary
        MovableClock movableClock() {
            return new MovableClock();
        }
    }

    @DynamicPropertySource
    static void properties(DynamicPropertyRegistry registry) {
        registry.add("compactor.endpoint-override", ArchiveCompactionIT::endpoint);
    }

    private static String endpoint() {
        return "http://" + MOTO.getHost() + ":" + MOTO.getMappedPort(5000);
    }

    private static S3Client s3;

    @BeforeAll
    static void bucket() {
        s3 = S3Client.builder()
                .region(Region.US_EAST_1)
                .endpointOverride(URI.create(endpoint()))
                .forcePathStyle(true)
                .credentialsProvider(StaticCredentialsProvider.create(AwsBasicCredentials.create("test", "test")))
                .build();
        s3.createBucket(b -> b.bucket(BUCKET));
    }

    @Autowired
    private FunctionCatalog catalog;

    @Autowired
    private MovableClock clock;

    @BeforeEach
    void clockIsOneHourAfterEverythingWrittenSoFar() {
        clock.set(Instant.now().plusSeconds(3600));
    }

    // ---- helpers ------------------------------------------------------------------------

    private CompactionReport run(String tenant) {
        Function<CompactionRequest, CompactionReport> function = catalog.lookup(Function.class, "compactArchive");
        return function.apply(new CompactionRequest(tenant, null));
    }

    private static void putRaw(String tenant, int hour, String name, int firstRecord, int count) throws IOException {
        var buffer = new ByteArrayOutputStream();
        try (var gz = new GZIPOutputStream(buffer)) {
            for (int i = 0; i < count; i++) {
                gz.write(("{\"n\":" + (firstRecord + i) + "}\n").getBytes(StandardCharsets.UTF_8));
            }
        }
        s3.putObject(
                b -> b.bucket(BUCKET).key(rawKey(tenant, hour, name)), RequestBody.fromBytes(buffer.toByteArray()));
    }

    private static String rawKey(String tenant, int hour, String name) {
        return "tenant=%s/dt=2026-01-15/hour=%02d/%s.ndjson.gz".formatted(tenant, hour, name);
    }

    private static List<S3Object> objects(String tenant) {
        return s3.listObjectsV2Paginator(b -> b.bucket(BUCKET).prefix("tenant=" + tenant + "/")).contents().stream()
                .toList();
    }

    private static List<String> keys(String tenant, String regex) {
        return objects(tenant).stream()
                .map(S3Object::key)
                .filter(k -> k.matches(regex))
                .toList();
    }

    private static long recordsIn(String key) throws IOException {
        try (var in = new GZIPInputStream(s3.getObject(b -> b.bucket(BUCKET).key(key)))) {
            return new String(in.readAllBytes(), StandardCharsets.UTF_8).lines().count();
        }
    }

    private static final String COMBINED = ".*/compacted-[0-9a-f]{16}\\.ndjson\\.gz";
    private static final String MANIFEST = ".*/compacted-[0-9a-f]{16}\\.manifest";
    private static final String RAW = ".*/(?!compacted-)[^/]+\\.ndjson\\.gz";

    // ---- tests --------------------------------------------------------------------------

    @Test
    @DisplayName("many small objects per hour become one object per hour, with every record kept")
    void compactsManySmallObjectsIntoOnePerHour() throws IOException {
        String tenant = "it-compacts";
        int expected = 0;
        for (int hour : new int[] {9, 10}) {
            for (int part = 0; part < 12; part++) {
                putRaw(tenant, hour, "part-%02d".formatted(part), expected, 5);
                expected += 5;
            }
        }

        CompactionReport report = run(tenant);

        assertThat(report.count(Status.COMPACTED)).isEqualTo(2);
        assertThat(keys(tenant, RAW)).isEmpty();
        List<String> combined = keys(tenant, COMBINED);
        assertThat(combined).hasSize(2);
        assertThat(keys(tenant, MANIFEST)).hasSize(2);
        long total = 0;
        for (String key : combined) {
            total += recordsIn(key);
        }
        assertThat(total).isEqualTo(expected);
    }

    @Test
    @DisplayName("a second run on compacted data leaves every object untouched")
    void secondRunLeavesEveryObjectUntouched() throws IOException {
        String tenant = "it-idempotent";
        for (int part = 0; part < 4; part++) {
            putRaw(tenant, 8, "part-" + part, part * 3, 3);
        }
        run(tenant);
        Map<String, String> before = etags(tenant);

        CompactionReport second = run(tenant);

        assertThat(second.count(Status.SKIPPED_NOTHING_TO_COMPACT)).isEqualTo(1);
        assertThat(etags(tenant)).isEqualTo(before);
    }

    @Test
    @DisplayName("a partition written to a moment ago is left alone")
    void partitionStillBeingWrittenIsLeftAlone() throws IOException {
        String tenant = "it-quiet";
        for (int part = 0; part < 3; part++) {
            putRaw(tenant, 7, "part-" + part, part, 1);
        }
        clock.set(Instant.now());

        CompactionReport report = run(tenant);

        assertThat(report.count(Status.SKIPPED_STILL_BEING_WRITTEN)).isEqualTo(1);
        assertThat(keys(tenant, RAW)).hasSize(3);
        assertThat(keys(tenant, COMBINED)).isEmpty();
    }

    @Test
    @DisplayName("sources left behind by an interrupted delete are removed by the next run, not merged again")
    void interruptedDeleteIsFinishedByTheNextRun() throws IOException {
        String tenant = "it-interrupted";
        for (int part = 0; part < 3; part++) {
            putRaw(tenant, 6, "part-" + part, part * 2, 2);
        }
        run(tenant);
        String combined = keys(tenant, COMBINED).get(0);
        String etag = etags(tenant).get(combined);
        // Recreate the state a crash mid-delete leaves: two sources the manifest names are back.
        putRaw(tenant, 6, "part-0", 0, 2);
        putRaw(tenant, 6, "part-1", 2, 2);
        assertThat(keys(tenant, RAW)).hasSize(2);

        CompactionReport report = run(tenant);

        assertThat(report.count(Status.CLEANED_UP)).isEqualTo(1);
        assertThat(keys(tenant, RAW)).isEmpty();
        assertThat(keys(tenant, COMBINED)).containsExactly(combined);
        assertThat(etags(tenant).get(combined)).isEqualTo(etag);
        assertThat(recordsIn(combined)).isEqualTo(6);
    }

    @Test
    @DisplayName("a run scoped to one tenant does not touch another")
    void scopedRunLeavesOtherTenantsAlone() throws IOException {
        for (int part = 0; part < 3; part++) {
            putRaw("it-scope-a", 5, "part-" + part, part, 1);
            putRaw("it-scope-b", 5, "part-" + part, part, 1);
        }

        run("it-scope-a");

        assertThat(keys("it-scope-a", COMBINED)).hasSize(1);
        assertThat(keys("it-scope-b", RAW)).hasSize(3);
        assertThat(keys("it-scope-b", COMBINED)).isEmpty();
    }

    private static Map<String, String> etags(String tenant) {
        return objects(tenant).stream().collect(Collectors.toMap(S3Object::key, S3Object::eTag));
    }
}
